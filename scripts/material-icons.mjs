// Copies the Material Symbols the app uses into src/lib/icons/material.ts, as their SVG path data, so only those
// icons are bundled. Add a name to ICONS (as Material names it, with "-fill" for the filled version) and run
// `npm run icons`. Every icon is a single path on the same 960-unit grid, drawn with ICON_VIEWBOX.

import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';

/** Which of Material Symbols' styles to use: 'outlined', 'rounded' or 'sharp'. */
const STYLE = 'rounded';

const ICONS = [
    // Actions
    'add', 'add_box', 'close', 'remove', 'check', 'edit', 'save', 'delete', 'undo', 'refresh', 'restart_alt', 'sync',
    'content_copy', 'download', 'upload', 'input', 'travel_explore', 'qr_code_2', 'visibility', 'fit_screen', 'photo_camera', 'lock', 'lock_open', 'tune', 'settings', 'cycle',
    // Navigation
    'arrow_back', 'arrow_forward', 'chevron_left', 'chevron_right', 'keyboard_arrow_up', 'keyboard_arrow_down', 'menu',
    'vertical_align_top', 'drag_handle',
    // Status
    'warning', 'warning-fill', 'info', 'star', 'star-fill', 'cloud_done', 'check_circle-fill', 'radio_button_unchecked',
    // Media
    'play_arrow-fill', 'pause-fill', 'stop-fill', 'skip_previous-fill', 'skip_next-fill',
    'volume_up-fill', 'volume_off-fill', 'music_note-fill', 'queue_music', 'playlist_play',
    // Drawing
    'ink_pen-fill', 'ink_eraser', 'ink_eraser-fill', 'layers', 'layers_clear',
    // The game
    'money_bag', 'menu_book', 'castle', 'dialpad', 'schedule', 'timer', 'sms', 'list', 'list_alt', 'sports_score',
    'donut_large', 'bar_chart', 'lightbulb', 'lightbulb-fill',
    // Times of day
    'wb_twilight-fill', 'sunny-fill', 'wb_twilight_2-fill', 'bedtime-fill',
];

const require = createRequire(import.meta.url);
const dir = join(dirname(require.resolve('@material-symbols/svg-400/package.json')), STYLE);

// "play_arrow-fill" becomes "playArrowFillIcon".
const exportName = (name) => name.replace(/[-_](\w)/g, (_, c) => c.toUpperCase()) + 'Icon';

const lines = ICONS.map(name => {
    const svg = readFileSync(join(dir, `${name}.svg`), 'utf8');
    const viewBox = svg.match(/viewBox="([^"]+)"/)?.[1];
    const paths = [...svg.matchAll(/<path d="([^"]+)"/g)].map(m => m[1]);
    if (viewBox !== '0 -960 960 960' || paths.length !== 1 || /<(circle|rect|g|polygon)\b/.test(svg)) {
        throw new Error(`${name} isn't a single path on the usual grid`);
    }
    return `/** ${name} */\nexport const ${exportName(name)} = ${JSON.stringify(paths[0])};`;
});

const out = `// Generated by scripts/material-icons.mjs from Material Symbols (${STYLE}, Apache 2.0); don't edit by hand.
// Each is an icon's SVG path, to draw as <path d={...}/> in an <svg viewBox={ICON_VIEWBOX}>.

export const ICON_VIEWBOX = '0 -960 960 960';

${lines.join('\n')}
`;
writeFileSync(new URL('../src/lib/icons/material.ts', import.meta.url), out);
console.log(`Wrote ${ICONS.length} icons`);
